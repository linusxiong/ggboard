/**
 * Per-component HeroUI CSS.
 *
 * `@import "@heroui/styles"` ships the CSS of all ~85 components (~390 KB, 35 KB br) as one
 * render-blocking file. This plugin instead attaches each component's stylesheet to the HeroUI
 * JS module that renders it, so a route only downloads CSS for components it actually renders
 * (tree-shaken modules drop their CSS import too). Feature code keeps importing from
 * `@heroui/react` as usual — nothing to remember.
 *
 * Each wrapper is compiled by Tailwind with `@reference` to the app stylesheet, so the
 * component's `@apply` / custom variants resolve against our theme, and is emitted into the
 * `components` cascade layer declared by `src/styles/index.css`.
 *
 * Overlay keyframes: since HeroUI 3.2.7 `@heroui/styles/base` imports `base/overlay-motion.css`, the
 * `heroui-overlay-*` keyframes its popovers, menus and dialogs animate with. No public page renders
 * one of those, and the entry stylesheet has to fit the first TCP round trip (web/README.md →
 * Performance rules). So the entry imports `.heroui-css/_base.css`, a copy of that base stylesheet
 * without the import, and the keyframes travel with the components that use them. A native element
 * that borrows one of those stylesheets adds `import 'heroui-css:overlay-motion'`.
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import path from 'node:path'
import type { Plugin } from 'vite'

const VIRTUAL_PREFIX = 'heroui-css:'
const COMPONENT_RE = /[\\/]@heroui[\\/]react[\\/]dist[\\/]components[\\/]([a-z-]+)[\\/][^\\/]+\.js$/
/** Generated files that are not a component start with `_` (component names are `[a-z-]+`). */
const BASE_FILE = '_base.css'
const OVERLAY_MOTION = 'overlay-motion'
const OVERLAY_MOTION_FILE = `_${OVERLAY_MOTION}.css`
const OVERLAY_MOTION_IMPORT = '@import "@heroui/styles/base/overlay-motion.css" layer(base);'
const BASE_OVERLAY_IMPORT_RE = /^@import\s+["']\.\/overlay-motion\.css["'];[ \t]*\r?\n/m
const GENERATED = '/* generated by scripts/heroui-css.ts — do not edit */'
/** A sublayer of `theme` ranks below everything else on the page, so these are defaults and never overrides. */
const TOKEN_LAYER = 'theme.heroui'
const COMMENT_RE = /\/\*[\s\S]*?\*\//g
/** `var(--x)` with no fallback: the declaration is void when nothing defines `--x`. */
const BARE_VAR_RE = /var\(\s*(--[\w-]+)\s*\)/g
const ANY_VAR_RE = /var\(\s*(--[\w-]+)/g

/**
 * `--name: value` pairs declared in the `@theme` blocks of a stylesheet. Only the names matter, and which other
 * theme variables a value mentions: the wrapper asks Tailwind for the value, so the app's own `@theme` wins.
 */
function themeDeclarations(css: string): Map<string, string> {
  const text = css.replace(COMMENT_RE, '')
  const declarations = new Map<string, string>()
  for (const at of text.matchAll(/@theme\b([^{;]*)\{/g)) {
    // `reference` blocks only feed utilities; Tailwind never emits them and the page defines those itself.
    if (/\breference\b/.test(at[1])) continue
    const start = at.index + at[0].length
    let end = start
    for (let depth = 1; depth > 0 && end < text.length; end++) {
      if (text[end] === '{') depth++
      else if (text[end] === '}') depth--
    }
    for (const [, name, value] of text.slice(start, end - 1).matchAll(/(--[\w-]+)\s*:\s*([^;{}]*);/g)) {
      declarations.set(name, value)
    }
  }
  return declarations
}

/** The theme variables `css` reads with a bare `var()`, plus the theme variables those are made of. */
function bareThemeVariables(css: string, theme: Map<string, string>): string[] {
  const found = new Set<string>()
  const queue = [...css.replace(COMMENT_RE, '').matchAll(BARE_VAR_RE)].map((m) => m[1])
  for (let name = queue.pop(); name; name = queue.pop()) {
    const value = theme.get(name)
    if (value === undefined || found.has(name)) continue
    found.add(name)
    queue.push(...[...value.matchAll(ANY_VAR_RE)].map((m) => m[1]))
  }
  return [...found].sort()
}

export function herouiComponentCss(): Plugin {
  let wrapperDir = ''
  let available = new Set<string>()
  let overlayMotion = new Set<string>()
  let isDev = false

  return {
    name: 'ggboard:heroui-component-css',
    enforce: 'pre',
    configResolved(config) {
      isDev = config.command === 'serve' && !config.isProduction
      const root = config.root
      wrapperDir = path.join(root, '.heroui-css')
      const require = createRequire(path.join(root, 'package.json'))
      const stylesPkg = path.dirname(require.resolve('@heroui/styles/package.json'))
      const componentsDir = path.join(stylesPkg, 'dist', 'components')
      available = new Set(
        readdirSync(componentsDir)
          .filter((f) => f.endsWith('.css') && f !== 'index.css')
          .map((f) => f.slice(0, -4)),
      )
      mkdirSync(wrapperDir, { recursive: true })

      const base = readFileSync(path.join(stylesPkg, 'dist', 'base', 'base.css'), 'utf8')
      const baseWithoutMotion = base.replace(BASE_OVERLAY_IMPORT_RE, '')
      // The copy lives in another directory, so any other relative import would not resolve either.
      if (baseWithoutMotion === base || /^@import\b/m.test(baseWithoutMotion)) {
        throw new Error(
          '[heroui-css] @heroui/styles/base changed its imports: check how it ships the overlay keyframes and update scripts/heroui-css.ts',
        )
      }
      writeFileSync(path.join(wrapperDir, BASE_FILE), `${GENERATED}\n${baseWithoutMotion}`)
      writeFileSync(path.join(wrapperDir, OVERLAY_MOTION_FILE), `${GENERATED}\n${OVERLAY_MOTION_IMPORT}\n`)
      overlayMotion = new Set(
        [...available].filter((name) =>
          readFileSync(path.join(componentsDir, `${name}.css`), 'utf8').includes('heroui-overlay-'),
        ),
      )

      const theme = new Map([
        ...themeDeclarations(readFileSync(require.resolve('tailwindcss/theme.css'), 'utf8')),
        ...themeDeclarations(
          readFileSync(path.join(stylesPkg, 'dist', 'themes', 'shared', 'theme.css'), 'utf8'),
        ),
      ])
      const reference = path
        .relative(wrapperDir, path.join(root, 'src', 'styles', 'index.css'))
        .split(path.sep)
        .join('/')
      for (const name of available) {
        const file = path.join(wrapperDir, `${name}.css`)
        const css = readFileSync(path.join(componentsDir, `${name}.css`), 'utf8')
        const tokens = bareThemeVariables(css, theme).map((v) => `    ${v}: --theme(${v} inline);\n`)
        const content = [
          GENERATED,
          `@reference "${reference}";`,
          `@import "@heroui/styles/components/${name}.css" layer(components);`,
          ...(tokens.length ? [`@layer ${TOKEN_LAYER} {\n  :root {\n${tokens.join('')}  }\n}`] : []),
          '',
        ].join('\n')
        writeFileSync(file, content)
      }
    },
    /** `import 'heroui-css:button'` — the component's CSS without its JS (for native elements). */
    resolveId(id) {
      if (!id.startsWith(VIRTUAL_PREFIX)) return null
      const name = id.slice(VIRTUAL_PREFIX.length)
      if (name === OVERLAY_MOTION) return path.join(wrapperDir, OVERLAY_MOTION_FILE)
      if (!available.has(name)) throw new Error(`[heroui-css] unknown HeroUI component stylesheet "${name}"`)
      return path.join(wrapperDir, `${name}.css`)
    },
    transform(code, id) {
      // Dev server: dependencies are pre-bundled (this hook never sees HeroUI's modules), so
      // simply load every component stylesheet. Production builds stay per-component.
      if (isDev && /[\\/]src[\\/]styles[\\/]index\.css(\?.*)?$/.test(id)) {
        return {
          code: `${code}\n${OVERLAY_MOTION_IMPORT}\n@import "@heroui/styles/components/index.css" layer(components);\n`,
          map: null,
        }
      }
      const match = COMPONENT_RE.exec(id)
      const name = match?.[1]
      if (!name || !available.has(name)) return null
      const wrapper = path.join(wrapperDir, `${name}.css`)
      if (!existsSync(wrapper)) return null
      const files = overlayMotion.has(name)
        ? [path.join(wrapperDir, OVERLAY_MOTION_FILE), wrapper]
        : [wrapper]
      return {
        code: `${files.map((file) => `import ${JSON.stringify(file)};`).join('\n')}\n${code}`,
        map: null,
      }
    },
  }
}
