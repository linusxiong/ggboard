/**
 * Per-component HeroUI CSS.
 *
 * `@import "@heroui/styles"` ships the CSS of all ~85 components (~390 KB, 35 KB br) as one
 * render-blocking file. This plugin instead attaches each component's stylesheet to the HeroUI
 * JS module that renders it, so a route only downloads CSS for components it actually renders
 * (tree-shaken modules drop their CSS import too). Feature code keeps importing from
 * `@heroui/react` as usual — nothing to remember.
 *
 * Each wrapper is compiled by Tailwind with `@reference` to the app stylesheet, so the
 * component's `@apply` / custom variants resolve against our theme, and is emitted into the
 * `components` cascade layer declared by `src/styles/index.css`.
 */
import { existsSync, mkdirSync, readdirSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import path from 'node:path'
import type { Plugin } from 'vite'

const VIRTUAL_PREFIX = 'heroui-css:'
const COMPONENT_RE = /[\\/]@heroui[\\/]react[\\/]dist[\\/]components[\\/]([a-z-]+)[\\/][^\\/]+\.js$/

export function herouiComponentCss(): Plugin {
  let wrapperDir = ''
  let available = new Set<string>()
  let isDev = false

  return {
    name: 'ggboard:heroui-component-css',
    enforce: 'pre',
    configResolved(config) {
      isDev = config.command === 'serve' && !config.isProduction
      const root = config.root
      wrapperDir = path.join(root, '.heroui-css')
      const require = createRequire(path.join(root, 'package.json'))
      const stylesPkg = path.dirname(require.resolve('@heroui/styles/package.json'))
      const componentsDir = path.join(stylesPkg, 'dist', 'components')
      available = new Set(
        readdirSync(componentsDir)
          .filter((f) => f.endsWith('.css') && f !== 'index.css')
          .map((f) => f.slice(0, -4)),
      )
      mkdirSync(wrapperDir, { recursive: true })
      const reference = path
        .relative(wrapperDir, path.join(root, 'src', 'styles', 'index.css'))
        .split(path.sep)
        .join('/')
      for (const name of available) {
        const file = path.join(wrapperDir, `${name}.css`)
        const content = `/* generated by scripts/heroui-css.ts — do not edit */\n@reference "${reference}";\n@import "@heroui/styles/components/${name}.css" layer(components);\n`
        writeFileSync(file, content)
      }
    },
    /** `import 'heroui-css:button'` — the component's CSS without its JS (for native elements). */
    resolveId(id) {
      if (!id.startsWith(VIRTUAL_PREFIX)) return null
      const name = id.slice(VIRTUAL_PREFIX.length)
      if (!available.has(name)) throw new Error(`[heroui-css] unknown HeroUI component stylesheet "${name}"`)
      return path.join(wrapperDir, `${name}.css`)
    },
    transform(code, id) {
      // Dev server: dependencies are pre-bundled (this hook never sees HeroUI's modules), so
      // simply load every component stylesheet. Production builds stay per-component.
      if (isDev && /[\\/]src[\\/]styles[\\/]index\.css(\?.*)?$/.test(id)) {
        return {
          code: `${code}\n@import "@heroui/styles/components/index.css" layer(components);\n`,
          map: null,
        }
      }
      const match = COMPONENT_RE.exec(id)
      const name = match?.[1]
      if (!name || !available.has(name)) return null
      const wrapper = path.join(wrapperDir, `${name}.css`)
      if (!existsSync(wrapper)) return null
      return { code: `import ${JSON.stringify(wrapper)};\n${code}`, map: null }
    },
  }
}
